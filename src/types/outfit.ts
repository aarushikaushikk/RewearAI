// Allowed outfit values, shared by the Mongoose models and the UI.
// Client-safe: no server imports.

import type { Category, Color, Formality, Season } from "@/types/wardrobe";

/** PRD §13 occasion categories. */
export const OCCASIONS = [
  "work",
  "dinner",
  "weekend",
  "casual",
  "formal",
] as const;

/** PRD US14: positive or negative; clearing feedback removes the record. */
export const FEEDBACK_RATINGS = ["positive", "negative"] as const;

export type Occasion = (typeof OCCASIONS)[number];
export type FeedbackRating = (typeof FEEDBACK_RATINGS)[number];

/** How an outfit's colors read together, calmest first (#18; see colorHarmony.ts). */
export const PALETTES = ["tonal", "neutral", "one_accent", "paired", "bold"] as const;
export type Palette = (typeof PALETTES)[number];

/** The part each item plays in a generated outfit (US7). */
export type OutfitRole = "top" | "bottom" | "dress" | "shoes" | "outerwear" | "accessory";

/**
 * Why no outfit could be generated (US7):
 * - `no_suitable_items`: none of the user's available items has a formality for the occasion.
 * - `no_complete_outfit`: suitable items exist, but no Top + Bottom or Dress can be formed.
 */
export type InsufficientReason = "no_suitable_items" | "no_complete_outfit";

/** A recommended wardrobe item, with what the Create Outfit page needs to show it. */
export interface OutfitItemDto {
  role: OutfitRole;
  id: string;
  /** Null when the user didn't name the item; display color and style instead. */
  name: string | null;
  image: { url: string };
  category: Category;
  color: Color;
  style: string;
  season: Season;
  formality: Formality;
}

/**
 * US13: the facts an outfit was chosen on, for the Why these items? panel. Facts only, never
 * sentences: the page writes the copy, so server text never reaches the user.
 */
export interface OutfitExplanationDto {
  /** The pieces' distinct formalities, in FORMALITIES order; each is allowed for the occasion. */
  formalities: Formality[];
  /** The pieces' distinct seasons, in SEASONS order: at most one specific season, plus All-season. */
  seasons: Season[];
  palette: Palette;
  /** True when generated by Try another, as a change from outfits already shown (US8). */
  alternative: boolean;
}

/** US14: the user's saved rating of an outfit, and the stored outfit it belongs to. */
export interface OutfitFeedbackDto {
  outfitId: string;
  rating: FeedbackRating;
}

/**
 * Response data for POST /api/outfits/generate. Generated outfits are not saved (US9).
 * `no_alternative` means every valid combination was among the outfits already shown (US8).
 */
export type OutfitRecommendationDto =
  | {
      status: "ok";
      occasion: Occasion;
      season: Season;
      items: OutfitItemDto[];
      explanation: OutfitExplanationDto;
      /** US14: the rating saved for exactly these items and this occasion, or null. */
      feedback: OutfitFeedbackDto | null;
    }
  | { status: "insufficient"; occasion: Occasion; reason: InsufficientReason }
  | { status: "no_alternative"; occasion: Occasion };

/** A saved outfit as stored (US9): references to the user's wardrobe items, never copies. */
export interface SavedOutfitRecord {
  id: string;
  ownerId: string;
  occasion: Occasion;
  itemIds: string[];
  savedAt: Date;
}

/** One item of a saved outfit; an item deleted since saving is only marked removed (US9). */
export type SavedOutfitItemDto =
  | {
      status: 'present';
      id: string;
      /** Null when the user didn't name the item; display color and style instead. */
      name: string | null;
      image: { url: string };
      category: Category;
      color: Color;
      style: string;
    }
  | { status: 'removed'; id: string };

/** A saved outfit as the Saved Outfits page shows it. */
export interface SavedOutfitDto {
  id: string;
  occasion: Occasion;
  /** ISO 8601. */
  savedAt: string;
  items: SavedOutfitItemDto[];
}
