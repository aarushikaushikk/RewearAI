import { describe, expect, it } from 'vitest';
import { explainOutfit } from '@/services/outfits/explainOutfit';
import type { Occasion } from '@/types/outfit';
import type { Color, Formality, Season } from '@/types/wardrobe';

type Piece = { item: { formality: Formality; season: Season; color: Color } };
const piece = (formality: Formality, season: Season = 'All-season', color: Color = 'Black'): Piece => ({
  item: { formality, season, color },
});

describe('explainOutfit (US13)', () => {
  it('lists the distinct formalities and seasons in canonical order, whatever the piece order', () => {
    const pieces = [piece('Formal', 'All-season'), piece('Smart casual', 'Autumn'), piece('Formal', 'Autumn')];

    const facts = explainOutfit('work', pieces, 'tonal', false);

    expect(facts).toEqual({
      formalities: ['Smart casual', 'Formal'],
      seasons: ['Autumn', 'All-season'],
      palette: 'tonal',
      alternative: false,
    });
    expect(explainOutfit('work', [...pieces].reverse(), 'tonal', false)).toEqual(facts);
  });

  it('marks an outfit generated by Try another', () => {
    expect(explainOutfit('casual', [piece('Casual')], 'tonal', true).alternative).toBe(true);
  });

  it('has exactly the four facts and nothing about the items themselves', () => {
    expect(Object.keys(explainOutfit('casual', [piece('Casual')], 'tonal', false)).sort()).toEqual([
      'alternative',
      'formalities',
      'palette',
      'seasons',
    ]);
  });

  it('checks that the palette matches the pieces', () => {
    const pieces = [piece('Casual', 'All-season', 'White'), piece('Casual', 'All-season', 'Navy')];

    expect(explainOutfit('casual', pieces, 'neutral', false).palette).toBe('neutral');
    expect(() => explainOutfit('casual', pieces, 'bold', false)).toThrow(RangeError);
  });

  it.each<[string, Occasion, Piece[]]>([
    ['no pieces', 'casual', []],
    ['a formality the occasion does not allow', 'formal', [piece('Casual')]],
    ['two specific seasons', 'casual', [piece('Casual', 'Summer'), piece('Casual', 'Winter')]],
  ])('refuses to explain %s, which the generator never produces', (_label, occasion, pieces) => {
    expect(() => explainOutfit(occasion, pieces, 'tonal', false)).toThrow(RangeError);
  });
});
